-- S15: immutable published content, hash-addressed resource bytes, a single
-- active pointer per channel and a release journal. Drafts stay separate.
CREATE FUNCTION ufagame_forbid_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'immutable row in %', TG_TABLE_NAME; END $$;

CREATE TABLE resource_blobs (
  sha256 text PRIMARY KEY CHECK (sha256 ~ '^[a-f0-9]{64}$'),
  media_type text NOT NULL CHECK (media_type IN ('image/png','audio/wav')),
  payload bytea NOT NULL CHECK (octet_length(payload) BETWEEN 1 AND 8388608),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER resource_blobs_immutable BEFORE UPDATE OR DELETE ON resource_blobs FOR EACH ROW EXECUTE FUNCTION ufagame_forbid_change();

CREATE TABLE content_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_version text NOT NULL UNIQUE CHECK (content_version ~ '^pub_[0-9]{6,}$'),
  sha256 text NOT NULL CHECK (sha256 ~ '^[a-f0-9]{64}$'),
  content jsonb NOT NULL CHECK (jsonb_typeof(content)='object'),
  resources jsonb NOT NULL CHECK (jsonb_typeof(resources)='array'),
  required_capabilities text[] NOT NULL,
  source_draft_id uuid NOT NULL,
  source_draft_revision integer NOT NULL CHECK (source_draft_revision >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER content_versions_immutable BEFORE UPDATE OR DELETE ON content_versions FOR EACH ROW EXECUTE FUNCTION ufagame_forbid_change();

CREATE TABLE content_pointer (
  channel text PRIMARY KEY CHECK (channel = 'test'),
  version_id bigint NOT NULL REFERENCES content_versions(id),
  revision integer NOT NULL CHECK (revision >= 1),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE content_releases (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  channel text NOT NULL CHECK (channel = 'test'),
  action text NOT NULL CHECK (action IN ('publish','rollback')),
  from_version_id bigint REFERENCES content_versions(id),
  to_version_id bigint NOT NULL REFERENCES content_versions(id),
  pointer_revision integer NOT NULL CHECK (pointer_revision >= 1),
  reason text NOT NULL CHECK (length(reason) BETWEEN 3 AND 300),
  request_id uuid NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER content_releases_immutable BEFORE UPDATE OR DELETE ON content_releases FOR EACH ROW EXECUTE FUNCTION ufagame_forbid_change();
